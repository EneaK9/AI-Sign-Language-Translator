"""Generate TypeScript interfaces from the FastAPI OpenAPI document.

openapi-typescript 7 does not run on TypeScript 7, so this script writes the
same component schemas into apps/web/src/api/schema.ts.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "apps" / "web" / "src" / "api" / "schema.ts"


def schema_type(schema: dict, required: bool = True) -> str:
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return name
    if "anyOf" in schema:
        options = [item for item in schema["anyOf"] if item.get("type") != "null"]
        nullable = any(item.get("type") == "null" for item in schema["anyOf"])
        rendered = " | ".join(schema_type(item) for item in options) or "unknown"
        if len(options) > 1:
            rendered = f"({rendered})"
        return f"{rendered} | null" if nullable else rendered
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        return f"{schema_type(schema.get('items', {}))}[]"
    if kind == "object":
        return "Record<string, unknown>"
    return "unknown"


def emit(spec: dict) -> str:
    lines = [
        "/* Generated by scripts/generate_api_types.py from the FastAPI OpenAPI schema.",
        "   openapi-typescript cannot run on this project's TypeScript 7 toolchain. */",
        "",
    ]
    schemas: dict = spec["components"]["schemas"]
    for name, schema in schemas.items():
        if name in {"HTTPValidationError", "ValidationError"}:
            continue
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        lines.append(f"export interface {name} {{")
        for prop, prop_schema in properties.items():
            optional = prop not in required
            rendered = schema_type(prop_schema)
            if optional and not rendered.endswith("| null"):
                lines.append(f"  {prop}?: {rendered};")
            else:
                lines.append(f"  {prop}: {rendered};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    source = sys.argv[1] if len(sys.argv) > 1 else ""
    if source:
        spec = json.loads(Path(source).read_text())
    else:
        with urllib.request.urlopen("http://127.0.0.1:8000/openapi.json", timeout=5) as response:
            spec = json.loads(response.read().decode())
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(emit(spec), encoding="utf-8")
    print(OUTPUT)


if __name__ == "__main__":
    main()
